The dungeon quests open only after the Riverglades zone chains against the Twilight's Hammer. Quest there first; this guide starts when those chains are done.

-- Prerequisites, done while questing in the Riverglades (zone quests, not in this guide):
-- Horde: The Wayward Warrior, Break Their Chains, Carving a Path, Rise Up!, Bring Me His Head (Da'grosh), then It Is Time, Brother... to Krom'rosh.
-- Alliance: Scraps of Knowledge, Curious Trinkets, A Small Favor (Ashe Amberhall); The Western Front, No Soldier Left Behind, Carving a Path, Bring Me His Head (Sergeant Riftan), News to Farholde.
-- Left out: 94891 News to Farholde and 94894 The Twilight Threat (zone chain, not dungeon quests).

