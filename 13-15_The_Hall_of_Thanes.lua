[N 13-15 The Hall of Thanes]
[NX 13-16 Ragefire Chasm]

[A Alliance] The dungeon lies under Ironforge. Six quests for Alliance; get the Dun Morogh chain first.
[A Horde] The dungeon lies under Ironforge, deep in Alliance land. Horde can only do the two neutral quests. The Ironforge guards may kill you on the way in, so expect a few ghost runs.

-- Alliance: Dun Morogh chain
[A Alliance] Fly to Ironforge [F Ironforge]
[A Alliance] Ride out of the gate and east along the road past Kharanos [G65.5,51.3 Dun Morogh]
[A Alliance] Kill Dark Iron Spies at Ironband's Compound until one drops the *Dark Iron Map*. Ghostfang, a level 10 elite, may roam the compound, so pull carefully [G76.2,60.8 Dun Morogh]
[A Alliance] Right-click the *Dark Iron Map* in your bags to accept [QA96391 Underground Map]
[A Alliance] Bring the map to Earthseer Farsen south of the road: turn in [QT96391 Underground Map], accept [QA96393 Old Ironforge Incursion] [G64.9,58.5 Dun Morogh]
[A Alliance] Ride back west on the road past Kharanos, round the lake [G60.6,47.2 Dun Morogh]
[A Alliance] Then north up the road to the Gates of Ironforge. A level 50 Plague Zombie may wander near the gate, so keep clear of it [G53.6,33.9 Dun Morogh]

-- Horde: the long run north
[A Horde] If you are not in Undercity yet, take the zeppelin there from the tower outside Orgrimmar. A level 30 elite Infernal and a level 12 elite Dustwind Eggtender may be near the tower, so stay on the path [G50.8,13.5 Durotar]
[A Horde] From Undercity run south through Silverpine Forest to Tarren Mill and pick up the flight point. Southshore Defenders (level 55) may patrol near the flight point, so keep away from them [P Tarren Mill] [G60.1,18.6 Hillsbrad Foothills]
[A Horde] Follow the road south-east past Durnholde Keep to the gate in Thoradin's Wall [G83.7,60 Hillsbrad Foothills]
[A Horde] Through the gate and down the road to the bend west of the Stromgarde turn-off [G26.3,50.1 Arathi Highlands]
[A Horde] Keep east on the road to the crossing south of Refuge Pointe [G45.2,58.4 Arathi Highlands]
[A Horde] Turn south and follow the road down to Thandol Span [G45.7,98.9 Arathi Highlands]
[A Horde] Cross Thandol Span and follow the road south through the pass to Dun Modr. The level 32 elites Modr and Neru stand at the gate, and raptors and rotclaws (level 23-26) roam the pass, so stay on the road and do not stop [G49.7,26 Wetlands]
[A Horde] Keep south to the river road. Dragonmaw and Nightveiled elites (level 28-32), the elite Golm and young crocolisks are by this road, so keep moving [G57,49.5 Wetlands]
[A Horde] Follow the river south to Dun Algaz. Mosshide gnolls (level 20-22) camp by the road here, so keep moving [G55.1,73.7 Wetlands]
[A Horde] Through the Dun Algaz tunnel into Loch Modan, then west at the junction to the North Gate Pass [G20.7,17.5 Loch Modan]
[A Horde] Through the tunnel into Dun Morogh and follow the road south past the North Gate Outpost [G77.2,49.9 Dun Morogh]
[A Horde] Keep west on the road past Kharanos [G65.5,51.3 Dun Morogh]
[A Horde] Follow the road west round the lake, not across it [G60.6,47.2 Dun Morogh]
[A Horde] Before the gate, consider taking your armor off: gear you are not wearing loses no durability if the guards kill you
[A Horde] Up the ramp to the Gates of Ironforge. A level 50 Plague Zombie may wander near the gate [G53.6,33.9 Dun Morogh]

-- Both: Old Ironforge
Go to the High Seat, Magni's throne room. Just inside, turn left into the webbed corridor that leads down to Old Ironforge [G43.5,52.0 Ironforge]
[A Alliance] Accept [QA96394 The Restless Dead] from Afadra Dunwall at the top of Old Ironforge, before you head down [G33.2,48.0 Ironforge]
Accept [QA96403 Important Heirlooms] from Thom Filch on the bridge beside the dungeon portal [G32.2,44.5 Ironforge]

-- Inside the dungeon
After the first room, accept [QA96395 An Ancient Grudge] from the Ghostly Attendant
Complete [QC96395 An Ancient Grudge] by killing Faldrim Anvilmar, the first boss (players report him in the next room), then go back to the Ghostly Attendant and turn in [QT96395 An Ancient Grudge]
[OC]Look for small heirloom objects on walls, chairs and tables all through the dungeon for [QC96403 Important Heirlooms]; the last room has the most, behind the vaults
[A Alliance] [OC]Kill Enraged Apparitions and Tormented Souls as you go for [QC96394 The Restless Dead]
[A Alliance] Kill Durgen Dirgehammer, the last boss, and loot his head for [QC96393 Old Ironforge Incursion]
[A Alliance] In his room, the Reliquary of Kings, open the vaults until you find a stone tablet. Use the tablet to accept [QA98423 The Treaty of Understanding]

